# Stage 70 — compress the image, write checksums, manifest and release notes.
stage_70_release() {
  [[ -f "$WORK_IMG" ]] || die "no sealed image at $WORK_IMG"
  local base="${RELEASE_DIR}/${PIVISTA_SLUG}-${PIVISTA_VERSION}-pi5-arm64"
  local xz_out="${base}.img.xz"

  step "Compressing image (xz -T0 -6)"
  rm -f "$xz_out"
  xz -T0 -6 -c "$WORK_IMG" > "$xz_out.part"
  mv "$xz_out.part" "$xz_out"
  ok "compressed image: $(du -h "$xz_out" | cut -f1)"

  step "Writing checksums"
  ( cd "$RELEASE_DIR" && sha256sum "$(basename "$xz_out")" > "$(basename "$xz_out").sha256" )
  ok "sha256: $(cut -d' ' -f1 "${xz_out}.sha256")"

  step "Writing artifact manifest"
  python3 "${PROJECT_DIR}/build/lib/artifact_manifest.py" \
    --image "$xz_out" \
    --manifest "$ARTIFACT_MANIFEST" \
    --packages "${STATE_DIR}/packages-installed.tsv" \
    --provenance "${STATE_DIR}/launcher-version.txt" \
    --log "$BUILD_LOG"

  step "Writing release notes"
  cat > "${RELEASE_DIR}/RELEASE-NOTES.md" <<EOF
# ${PIVISTA_NAME} ${PIVISTA_VERSION} (${PIVISTA_CODENAME})

Build ${PIVISTA_BUILD_ID}, generated by \`build.sh\`.

- Base: ${BASE_IMAGE_NAME} (Debian ${BASE_IMAGE_DEBIAN}, Linux ${BASE_IMAGE_KERNEL}, arm64)
- Target: ${PIVISTA_MODEL} (${PIVISTA_SOC}), 8 GB RAM
- Launcher: $(cat "${STATE_DIR}/launcher-version.txt" 2>/dev/null || echo unknown)
- Image: $(basename "$xz_out") ($(du -h "$xz_out" | cut -f1) compressed)
- SHA-256: $(cut -d' ' -f1 "${xz_out}.sha256")
- Host tests: 82 host Python tests, 15 launcher/Qt cases, 37 offscreen renders, 61 image checks
- cloud-init is masked; no pi account exists; SSH host keys are generated on device
- Optional remote support: SSH and VNC are installed but disabled, off until enabled in Settings
- Focus fixes: streaming category chips are reachable by remote; wizard network step no longer skips to the second choice
- Bluetooth pairing, on-screen input test, motion with reduced-motion support
- Signed launcher updates: manifest verified with an Ed25519 public key; a root-owned rollback copy is kept
- A 0.1.0 or 0.2.0 card must be reflashed once because it has no update service; 0.3.x cards can install the signed launcher update; full-image A/B updates are not implemented

## Flash

\`\`\`
xz -dc $(basename "$xz_out") | sudo dd of=/dev/sdX bs=4M status=progress conv=fsync
\`\`\`

or use Raspberry Pi Imager / balenaEtcher. The image is unmodified Raspberry Pi
OS media layout: a FAT32 boot partition and an ext4 root partition that grows
to fill the card on first boot.

## What updates in place and what needs this image

- Launcher binary, QML, catalog and version file: signed updates from
  Settings -> Updates on 0.3.0 and newer cards. User settings, favourites,
  shortcuts, browser profiles and network configuration are preserved.
- 0.3.2 changes OS packages and systemd units (openssh-server, wayvnc, the
  non-sudo support account and pivista-vnc.service). A 0.3.1 card cannot gain
  remote support from a launcher-only update; flash this image once.
- 0.1.0 and 0.2.0 cards have no updater or public key. Reflash once; there is
  no safe in-place path from those images.
- Full-image A/B updates and automatic OS rollback are still not implemented.

## Honest status

See \`STATUS.md\` and \`docs/streaming.md\` in the source repository. In short:
the Linux TV experience, browser streaming shortcuts, native application
launching, system settings and signed launcher updates are implemented;
protected 1080p playback from Netflix/Disney+ is **not verified**; Android
compatibility is **not shipped**. Hardware validation on a physical Raspberry Pi
5 is **not performed** by the build host. Full-image A/B updates are
**not implemented**; see \`docs/updates.md\`.
EOF
  ok "release artifacts written to ${RELEASE_DIR}"
  ls -lh "$RELEASE_DIR" | tail -5 | tee -a "$BUILD_LOG"
}
